"""Bridge FIRERPA's xfrpc CLI to the pinned BK Android FRP client.

Executed by the existing FIRERPA supervisor; it does not start another daemon,
change credentials, or restart the phone. The native client owns reconnection.
"""
import os
import json
from pathlib import Path
import sys
import tempfile
import tomllib


def recovery_config(source):
    """Preserve native identity/proxies; bound detection of dead mobile TCP paths."""
    config = tomllib.loads(Path(source).read_text())
    transport = config.setdefault('transport', {})
    # Keep native-client protocol compatibility; bounded retries and live-path
    # detection do not require disabling multiplexing fleet-wide.
    transport.update(tcpMux=True, tcpMuxKeepaliveInterval=5, heartbeatInterval=3,
                     heartbeatTimeout=10, dialServerTimeout=3, dialServerKeepAlive=5)
    config['loginFailExit'] = False
    return config


def write_recovery_config(source, directory):
    # The native TOML is regenerated by FIRERPA. Derive this file on every launch,
    # rather than editing a temporary native config and losing the fix on restart.
    directory = Path(directory)
    target = directory / 'frpc-recovery.json'
    fd, name = tempfile.mkstemp(prefix='.frpc-recovery-', dir=directory)
    try:
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, 'w') as out:
            json.dump(recovery_config(source), out)
            out.flush()
            os.fsync(out.fileno())
        os.replace(name, target)
    finally:
        if os.path.exists(name):
            os.unlink(name)
    return str(target)


def official_args(argv):
    result = []
    i = 0
    while i < len(argv):
        arg = argv[i]
        if arg in ('-f', '-s'):
            pass  # Official frpc already stays in the foreground.
        elif arg in ('-v', '--version'):
            return ['--version']
        elif arg in ('-h', '--help'):
            return ['--help']
        elif arg == '-c' and i + 1 < len(argv):
            i += 1
            result.extend(['-c', argv[i]])
        else:
            raise ValueError('Unsupported forwarding client argument')
        i += 1
    if '-c' not in result:
        raise ValueError('Missing forwarding configuration')
    return result


def main():
    binary = Path(os.environ['USRDIR']) / 'phone-pilot/frpc-0.72.0-bk.1-android-arm64'
    args = official_args(sys.argv[1:])
    if '-c' in args:
        index = args.index('-c') + 1
        args[index] = write_recovery_config(args[index], binary.parent)
    os.execv(str(binary), [str(binary), *args])


if __name__ == '__main__':
    try:
        main()
    except (KeyError, ValueError, OSError):
        # Never echo command/config values: they can contain device credentials.
        print('BK forwarding adapter: invalid installation or arguments', file=sys.stderr)
        sys.exit(1)
